#!/bin/bash
# Generate /etc/kernel/config.d/30-server-localmod.config:
# "# CONFIG_X is not set" for every module the running system doesn't use.
#
# usage: gen-fragment.sh <configured-kernel-src> <base .config> <out fragment>
#   <base .config>: the config the ebuild produces WITH 10-/20- fragments applied,
#   e.g. from `ebuild cachyos-kernel-X.ebuild clean configure` -> work/modprep/.config
#
# Only ever turns =m into "not set". New modules in future kernels stay at the
# CachyOS default (=m), so the fragment errs on the side of building too much.
set -euo pipefail
src=$(realpath "$1"); base=$(realpath "$2"); out=$3
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

# lsmod-format list: currently loaded + keep-modules.txt
{ echo "Module Size Used by"
  awk '{print $1, 0, 0}' /proc/modules
  grep -vE '^\s*(#|$)' "$here/keep-modules.txt" | awk '{print $1, 0, 0}'
} | sort -u -k1,1 > "$tmp/lsmod"

cp "$base" "$tmp/.config"
# streamline_config.pl reads ./.config; Kconfig 'source' lines need srctree/SRCARCH.
( cd "$tmp" && srctree="$src" SRCARCH=x86 ARCH=x86 LSMOD="$tmp/lsmod" \
    perl "$src/scripts/kconfig/streamline_config.pl" --localmodconfig "$src" Kconfig \
    > "$tmp/localmod.config" 2> "$tmp/streamline.log" ) \
  || { cat "$tmp/streamline.log" >&2; exit 1; }

# Symbols defined in kept subtrees, plus keep-configs.txt
: > "$tmp/keep-syms"
grep -vE '^\s*(#|$)' "$here/keep-subtrees.txt" | while read -r d; do
    find "$src/$d" -name 'Kconfig*' -exec grep -hoE '^\s*(menu)?config\s+[A-Z0-9_]+' {} + \
        | awk '{print "CONFIG_" $2}' >> "$tmp/keep-syms"
done
grep -vE '^\s*(#|$)' "$here/keep-configs.txt" >> "$tmp/keep-syms"
sort -u -o "$tmp/keep-syms" "$tmp/keep-syms"

# =m in base, "not set" after streamlining, not in a kept subtree
grep -E '^CONFIG_[A-Z0-9_]+=m$' "$base" | cut -d= -f1 | sort > "$tmp/base-m"
grep -E '^# CONFIG_[A-Z0-9_]+ is not set$' "$tmp/localmod.config" | awk '{print $2}' | sort > "$tmp/lm-off"
comm -12 "$tmp/base-m" "$tmp/lm-off" | comm -23 - "$tmp/keep-syms" > "$tmp/off"

{
  echo "# Generated by localmod/gen-fragment.sh on $(date -I) from $(uname -r)."
  echo "# Disables every module not loaded at generation time, except"
  echo "# localmod/keep-{modules,configs,subtrees}.txt."
  echo "# Regenerate instead of hand-editing; to restore one driver, add it to keep-modules.txt."
  sed 's/^\(.*\)$/# \1 is not set/' "$tmp/off"
} > "$out"
echo "wrote $out: $(wc -l < "$tmp/off") modules disabled ($(wc -l < "$tmp/base-m") were =m)" >&2
grep -i 'not found' "$tmp/streamline.log" | sed 's/^/  streamline: /' >&2 || true
